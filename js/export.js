// Schematic export: a clean sheet with border, title block and parts list, as SVG or PNG.
import { DEFS, circuitBounds, valueText, fmt } from './model.js';
import { buildNetlist } from './netlist.js';
import { el, drawStatic, SVG_CSS } from './render.js';
import { download } from './storage.js';

const PRINT_VARS = '--ink:#111827;--body:#ffffff;--wire0:#111827;--dim:#6b7280;--accent:#2563eb;--pin:#b5573f;--flow:#2563eb;';
const MONO = 'ui-monospace,Menlo,Consolas,monospace';
const SKIP_BOM = new Set(['ground', 'vcc', 'netlabel', 'probe']);

export const DEFAULT_EXPORT = { values: true, bom: true, colorWires: false, readouts: false };

function bomRows(circ) {
  const nat = (a, b) => a.label.localeCompare(b.label, undefined, { numeric: true });
  return circ.components.filter((c) => !SKIP_BOM.has(c.type)).sort(nat)
    .map((c) => [c.label, DEFS[c.type].label, valueText(c) || '—']);
}

export function buildSchematic(circ, sim, opts = {}) {
  const o = { ...DEFAULT_EXPORT, ...opts };
  const nl = buildNetlist(circ);
  const g = drawStatic(circ, nl, o.colorWires ? sim : null, { colorWires: o.colorWires, labels: o.values });
  const b = circuitBounds(circ) || { x0: 0, y0: 0, x1: 360, y1: 140 };
  for (const r of g.labelRects) { b.x0 = Math.min(b.x0, r.x0); b.y0 = Math.min(b.y0, r.y0); b.x1 = Math.max(b.x1, r.x1); b.y1 = Math.max(b.y1, r.y1); }
  const pad = 56;
  let minX = b.x0 - pad, minY = b.y0 - pad, maxX = b.x1 + pad, maxY = b.y1 + pad;
  const tbW = 330, tbH = 66;
  maxX = Math.max(maxX, minX + tbW + 60);

  // parts list in columns under the drawing
  const rows = o.bom ? bomRows(circ) : [];
  const perCol = 12, colW = 270, lh = 13;
  const cols = Math.ceil(rows.length / perCol);
  const bomH = rows.length ? Math.min(rows.length, perCol) * lh + 30 : 0;
  maxX = Math.max(maxX, minX + cols * colW + 40);
  const W = maxX - minX;
  const notice = 'Educational use only. Generated by Circuitwright; no warranty. Verify every design and component rating before building. Not for mains voltage, high current, batteries or any safety critical use.';
  // Wrap to the sheet: 8px monospace is about 0.62em per character in the worst fallback font.
  const maxChars = Math.max(20, Math.floor((W - 36) / (8 * 0.62)));
  const foot = [];
  let line = '';
  for (const word of notice.split(' ')) {
    if (line && (line + ' ' + word).length > maxChars) { foot.push(line); line = word; }
    else line = line ? line + ' ' + word : word;
  }
  if (line) foot.push(line);
  const footH = foot.length * 11 + 10;
  const drawBottom = maxY;
  maxY = drawBottom + bomH + Math.max(tbH, 0) + footH + 14;
  const H = maxY - minY;

  const svg = el('svg', { xmlns: 'http://www.w3.org/2000/svg', width: W, height: H, viewBox: `${minX} ${minY} ${W} ${H}`, style: PRINT_VARS });
  const style = el('style');
  style.textContent = SVG_CSS;
  svg.append(style, el('rect', { x: minX, y: minY, width: W, height: H, fill: '#fff' }));
  svg.append(el('rect', { x: minX + 8, y: minY + 8, width: W - 16, height: H - 16, fill: 'none', stroke: '#111827', 'stroke-width': 1.5 }));
  svg.append(g);
  if (!o.values) for (const t of g.querySelectorAll('.lbl')) t.remove();
  const text = (s, x, y, size, weight = 600, fill = '#111827', anchor = 'start') => {
    const t = el('text', { x, y, 'font-family': MONO, 'font-size': size, 'font-weight': weight, fill, 'text-anchor': anchor });
    t.textContent = s;
    return t;
  };

  // parts list
  if (rows.length) {
    const y0 = drawBottom + 8;
    svg.append(text('PARTS LIST', minX + 20, y0 + 4, 10, 700));
    svg.append(el('line', { x1: minX + 20, y1: y0 + 10, x2: maxX - 20, y2: y0 + 10, stroke: '#9ca3af' }));
    rows.forEach((r, i) => {
      const cx = minX + 20 + Math.floor(i / perCol) * colW, cy = y0 + 24 + (i % perCol) * lh;
      svg.append(text(r[0], cx, cy, 10, 700));
      svg.append(text(r[1], cx + 42, cy, 10, 500, '#374151'));
      svg.append(text(r[2], cx + colW - 24, cy, 10, 500, '#6b7280', 'end'));
    });
  }

  // title block
  const tx = maxX - 8 - tbW, ty = maxY - 8 - footH - tbH;
  svg.append(el('rect', { x: tx, y: ty, width: tbW, height: tbH, fill: '#fff', stroke: '#111827', 'stroke-width': 1.5 }));
  svg.append(el('line', { x1: tx, y1: ty + 26, x2: tx + tbW, y2: ty + 26, stroke: '#111827' }));
  svg.append(el('line', { x1: tx, y1: ty + 44, x2: tx + tbW, y2: ty + 44, stroke: '#9ca3af' }));
  svg.append(text(('CIRCUITWRIGHT: ' + (circ.title || 'Untitled')).slice(0, 38).toUpperCase(), tx + 10, ty + 18, 12, 700));
  const stats = [['DATE', new Date().toISOString().slice(0, 10), 130], ['PARTS', String(rows.length), 100], ['WIRES', String(circ.wires.length), 100]];
  let off = 0;
  for (const [label, value, w] of stats) {
    if (off) svg.append(el('line', { x1: tx + off, y1: ty + 26, x2: tx + off, y2: ty + tbH, stroke: '#111827' }));
    svg.append(text(label, tx + off + 8, ty + 39, 9, 600, '#6b7280'));
    svg.append(text(value, tx + off + 8, ty + 57, 11, 700));
    off += w;
  }
  const fy = maxY - 8 - footH;
  svg.append(el('line', { x1: minX + 8, y1: fy, x2: maxX - 8, y2: fy, stroke: '#111827', 'stroke-width': 1.5 }));
  foot.forEach((ln, i) => svg.append(text(ln, minX + 18, fy + 14 + i * 11, 8, 600, '#6b7280')));
  void fmt;
  return { svg: new XMLSerializer().serializeToString(svg), width: W, height: H };
}

function rasterize(svg, width, height, name, scale = 2) {
  const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
  const img = new Image();
  img.onload = () => {
    const cv = document.createElement('canvas');
    const k = Math.min(scale, 16000 / Math.max(width, height));
    cv.width = Math.round(width * k);
    cv.height = Math.round(height * k);
    const ctx = cv.getContext('2d');
    ctx.fillStyle = '#fff';
    ctx.fillRect(0, 0, cv.width, cv.height);
    ctx.drawImage(img, 0, 0, cv.width, cv.height);
    URL.revokeObjectURL(url);
    cv.toBlob((b) => download(b, name), 'image/png');
  };
  img.src = url;
}

const slug = (c) => (c.title || 'schematic').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'schematic';

export function exportSVG(circ, sim, opts) {
  download(new Blob([buildSchematic(circ, sim, opts).svg], { type: 'image/svg+xml' }), `circuitwright-${slug(circ)}.svg`);
}

export function exportPNG(circ, sim, opts, scale = 2) {
  const { svg, width, height } = buildSchematic(circ, sim, opts);
  rasterize(svg, width, height, `circuitwright-${slug(circ)}.png`, scale);
}
